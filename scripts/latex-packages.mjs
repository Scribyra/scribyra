// Writes web/latex-packages.js: the LaTeX package names (.sty files under tex/latex)
// in the pinned TeX Live catalog, for \usepackage completion. Run after `npm run tex:catalog`.
//   node scripts/latex-packages.mjs [--check]
import {readFileSync,writeFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
export function latexPackageList(catalog){
  const names=new Set();
  for(const pkg of Object.values(catalog.packages))for(const file of pkg.files||[]){
    const match=/^tex\/latex\/.+\/([A-Za-z0-9][A-Za-z0-9._-]*)\.sty$/.exec(file);if(match)names.add(match[1]);
  }
  return {snapshot:catalog.snapshot,packages:[...names].sort((a,b)=>a.localeCompare(b,'en'))};
}
if(import.meta.url===`file://${process.argv[1]}`){
  const catalog=JSON.parse(gunzipSync(readFileSync(new URL('../web/tex-catalog.json.gz',import.meta.url))));
  const text='// Generated by scripts/latex-packages.mjs from web/tex-catalog.json.gz. Do not edit.\nexport default '+JSON.stringify(latexPackageList(catalog))+';\n',target=new URL('../web/latex-packages.js',import.meta.url);
  if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==text){console.error('web/latex-packages.js is out of date: run node scripts/latex-packages.mjs');process.exit(1);}}
  else writeFileSync(target,text);
}
